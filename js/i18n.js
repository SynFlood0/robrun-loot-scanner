export function formatMoney(n, lang = "en") {
  if (!n && n !== 0) return "—";
  return lang === "de"
    ? `${Math.round(n).toLocaleString("de-DE")} $`
    : `$${Math.round(n).toLocaleString("en-US")}`;
}

export function formatColShort(slug, lang = "en") {
  const [grp, num] = slug.split("-");
  const prefixMap = lang === "de"
    ? { basic: "G", additional: "Z", special: "B", unique: "E" }
    : { basic: "B", additional: "A", special: "S", unique: "U" };
  return `${prefixMap[grp] || grp[0].toUpperCase()}${num}`;
}

export function formatColFull(slug, lang = "en") {
  const [grp, num] = slug.split("-");
  const cap = grp.charAt(0).toUpperCase() + grp.slice(1);
  const gName = I18N[lang].groups[cap] || cap;
  return `${gName} #${num}`;
}
